export function uiText(text: string): string {
  return Object.hasOwn(SYSTEM_COPY, text) ? SYSTEM_COPY[text] : text;
}

export function uiLabel(value: string): string {
  return Object.hasOwn(LABELS, value)
    ? LABELS[value]
    : value.replaceAll("_", " ").replace(/^./, (letter) => letter.toUpperCase());
}

export function sourceLabel(tier: number): string {
  if (tier === 1) return "Company-related website";
  if (tier === 2) return "News or official records";
  return "Other website";
}
